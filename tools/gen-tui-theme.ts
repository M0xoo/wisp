// Generates the TUI's colours from @wisp/tokens: packages/tokens/tokens/color.json →
// plugins/tui/api/src/tokens.rs (committed; a test in plugins/tui/api checks it against color.json).
// rgba tokens (accent-soft, add-bg…) are composited over the theme's own `bg`, since a terminal cell has
// one solid colour.
//
//   node tools/gen-tui-theme.ts            write it
//   node tools/gen-tui-theme.ts --check    exit 1 when the file is out of date

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const src = `${root}packages/tokens/tokens/color.json`;
const out = `${root}plugins/tui/api/src/tokens.rs`;
const GROUPS = ['surface', 'ink', 'line', 'accent', 'state', 'diff', 'term', 'syntax', 'project'];

type Leaf = { light: string; dark: string };
const json = JSON.parse(readFileSync(src, 'utf8')) as Record<string, Record<string, Leaf | string>>;

function rgb(v: string, over: [number, number, number]): [number, number, number] {
  const hex = /^#([0-9a-f]{6})$/i.exec(v);
  if (hex) {
    const n = parseInt(hex[1]!, 16);
    return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
  }
  const m = /^rgba?\(\s*(\d+),\s*(\d+),\s*(\d+)(?:,\s*([\d.]+))?\s*\)$/.exec(v);
  if (!m) throw new Error(`a colour this generator can't read: ${v}`);
  const a = m[4] === undefined ? 1 : Number(m[4]);
  return [1, 2, 3].map((i, k) => Math.round(Number(m[i]) * a + over[k]! * (1 - a))) as [number, number, number];
}

const leaves: [string, Leaf][] = [];
for (const g of GROUPS) for (const [k, v] of Object.entries(json[g] ?? {})) if (!k.startsWith('$') && typeof v === 'object') leaves.push([k, v]);
const field = (k: string): string => k.replace(/-/g, '_');
const hexOf = (c: [number, number, number]): string => `0x${c.map((x) => x.toString(16).padStart(2, '0')).join('')}`;

function theme(mode: 'light' | 'dark'): string {
  const bg = rgb((json['surface']!['bg'] as Leaf)[mode], [0, 0, 0]);
  return leaves.map(([k, v]) => `        ${field(k)}: hex(${hexOf(rgb(v[mode], bg))}),`).join('\n');
}

const text = `// @generated by tools/gen-tui-theme.ts from packages/tokens/tokens/color.json. Don't edit: run
// \`node tools/gen-tui-theme.ts\`. rgba tokens are composited over the theme's \`bg\`.

#![allow(clippy::unreadable_literal)]

use ratatui::style::Color;

/// \`#rrggbb\` as a colour.
pub const fn hex(h: u32) -> Color {
    Color::Rgb(((h >> 16) & 0xff) as u8, ((h >> 8) & 0xff) as u8, (h & 0xff) as u8)
}

/// Every colour token, one theme's values.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Tokens {
${leaves.map(([k]) => `    pub ${field(k)}: Color,`).join('\n')}
}

/// Each token's name in color.json, with its value (the drift test reads these).
impl Tokens {
    pub fn pairs(&self) -> Vec<(&'static str, Color)> {
        vec![${leaves.map(([k]) => `("${k}", self.${field(k)})`).join(', ')}]
    }
}

pub const DARK: Tokens = Tokens {
${theme('dark')}
};

pub const LIGHT: Tokens = Tokens {
${theme('light')}
};
`;

if (process.argv.includes('--check')) {
  const had = readFileSync(out, 'utf8');
  if (had !== text) {
    console.error(`${out} is out of date: node tools/gen-tui-theme.ts`);
    process.exit(1);
  }
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${leaves.length} tokens)`);
}
