// wisp's TypeScript/JavaScript SDK (ADR-0028): everything a frontend can do, from Node or anything with fetch.
// Every call is a command (POST /api/cmd, with an idempotency key) or a topic subscription (the sync stream,
// GET /api/events), so permissions, idempotency and live updates behave as they do in the app. Zero dependencies.
//
//   import { WispClient } from 'wisp-agents/client';
//   const w = await WispClient.connect();                       // the running wisp, or one started for you
//   const t = await w.run({ prompt: 'fix the flaky auth test', cwd: process.cwd() });
//   const done = await w.wait(t.id);                            // until it stops working (live, not polled)
//   console.log((await w.presentation(done.id))?.blocks);
//   await w.cmd('runtime.followUp', { id: t.id, text: 'and add a test' });   // any command in the catalogue
//
// Types for every command come from the running wisp: `generateTypes(await w.catalogue())`.

import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { randomBytes } from 'node:crypto';
import { fileURLToPath } from 'node:url';

export const DEFAULT_PORT = 4477;
/** The sync protocol this SDK speaks (wisp-protocol PROTO_MIN..PROTO). */
export const PROTO = 2;
const BIN = fileURLToPath(new URL('./bin/wisp.js', import.meta.url));

export const wispHome = () => process.env.WISP_HOME || path.join(os.homedir(), '.wisp');

/** The port the running wisp advertises in `<home>/server.json`, or null. */
export function discover(home = wispHome()) {
  try {
    const info = JSON.parse(fs.readFileSync(path.join(home, 'server.json'), 'utf8'));
    return Number.isInteger(info.port) ? info.port : null;
  } catch {
    return null;
  }
}

/** A refusal in wisp's own words: `code` (`invalid`, `forbidden`, `not_found`, `conflict`, …), and whether a retry may help. */
export class WispError extends Error {
  constructor(message, { code = 'internal', status = 0, retry = false, body = null } = {}) {
    super(message);
    this.name = 'WispError';
    Object.assign(this, { code, status, retry, body });
  }
}

const key = () => `sdk-${randomBytes(12).toString('hex')}`;

/** SSE, chunk by chunk (a frame may split anywhere): `push(text)` → `[{ event, id, data }]`. */
export class SseParser {
  #buf = '';
  #ev = { event: '', id: null, data: [] };
  push(text) {
    this.#buf += text;
    const out = [];
    for (let i; (i = this.#buf.search(/\r?\n/)) >= 0; ) {
      const line = this.#buf.slice(0, i);
      this.#buf = this.#buf.slice(i + (this.#buf[i] === '\r' ? 2 : 1));
      if (line === '') {
        if (this.#ev.data.length) out.push({ event: this.#ev.event || 'message', id: this.#ev.id, data: this.#ev.data.join('\n') });
        this.#ev = { event: '', id: this.#ev.id, data: [] };
      } else if (!line.startsWith(':')) {
        const c = line.indexOf(':');
        const [field, value] = c < 0 ? [line, ''] : [line.slice(0, c), line.slice(c + 1).replace(/^ /, '')];
        if (field === 'data') this.#ev.data.push(value);
        else if (field === 'event') this.#ev.event = value;
        else if (field === 'id') this.#ev.id = value;
      }
    }
    return out;
  }
}

/** A sync frame's server messages (`welcome`, `snapshot`, `patch`, …), or null for anything else. */
export function decodeFrame(ev) {
  if (ev.event !== 'sync') return null;
  try {
    const messages = JSON.parse(ev.data);
    return Array.isArray(messages) ? messages : null;
  } catch {
    return null;
  }
}

const IDENT = /^[A-Za-z_$][\w$]*$/;
const prop = (k) => (IDENT.test(k) ? k : JSON.stringify(k));

/** A `.d.ts` for the commands a catalogue lists: `WispCommands` (id → args and result), and `cmd`'s overload. */
export function generateTypes(catalogue) {
  const lines = ['// Generated by wisp-agents generateTypes() from a running wisp\'s catalogue. Do not edit.', 'export interface WispCommands {'];
  for (const c of [...catalogue].sort((a, b) => a.id.localeCompare(b.id))) {
    if (c.uiOnly) continue;
    if (c.title) lines.push(`  /** ${String(c.title).replace(/\*\//g, '* /')}${c.readOnly ? ' (read only)' : ''} */`);
    lines.push(`  ${prop(c.id)}: { args: ${c.args || 'Record<string, unknown>'}; result: unknown };`);
  }
  lines.push('}', '', "declare module 'wisp-agents/client' {", '  interface WispClient {', '    cmd<K extends keyof WispCommands>(id: K, args: WispCommands[K][\'args\'], opts?: { key?: string }): Promise<WispCommands[K][\'result\']>;', '  }', '}', '');
  return lines.join('\n');
}

export class WispClient {
  /** `url`: `http://127.0.0.1:<port>` (or a peer's); `token`: `WISP_TOKEN` when it asks for one. */
  constructor({ url = `http://127.0.0.1:${DEFAULT_PORT}`, token = process.env.WISP_TOKEN || '' } = {}) {
    this.url = url.replace(/\/+$/, '');
    this.token = token;
    this.clientId = `sdk-${randomBytes(8).toString('hex')}`;
  }

  /** The running wisp (`server.json`), or one started with `wisp serve` when `start` and none answers. */
  static async connect({ url, port, home = wispHome(), token, start = true, timeoutMs = 15_000 } = {}) {
    const found = url || `http://127.0.0.1:${port || discover(home) || DEFAULT_PORT}`;
    const c = new WispClient({ url: found, token });
    if (await c.alive()) return c;
    if (!start || url) throw new WispError(`No wisp answers at ${found}. Start one with: wisp serve`, { code: 'unavailable', retry: true });
    spawn(process.execPath, [BIN, 'serve'], { detached: true, stdio: 'ignore', env: { ...process.env, WISP_HOME: home } }).unref();
    const until = Date.now() + timeoutMs;
    while (Date.now() < until) {
      await new Promise((r) => setTimeout(r, 200));
      const p = discover(home);
      const next = p ? new WispClient({ url: `http://127.0.0.1:${p}`, token }) : c;
      if (await next.alive()) return next;
    }
    throw new WispError(`wisp didn’t start within ${Math.round(timeoutMs / 1000)} s`, { code: 'unavailable', retry: true });
  }

  #headers(extra = {}) {
    return { ...(this.token && { 'x-wisp-token': this.token }), ...extra };
  }

  async alive() {
    try {
      const r = await fetch(`${this.url}/api/health`, { headers: this.#headers(), signal: AbortSignal.timeout(2000) });
      return r.ok;
    } catch {
      return false;
    }
  }

  /** One command: its result, or a `WispError` in wisp's words. The same `key` makes a retry one command. */
  async cmd(id, args = {}, { key: k = key(), signal } = {}) {
    let r;
    try {
      r = await fetch(`${this.url}/api/cmd`, { method: 'POST', headers: this.#headers({ 'content-type': 'application/json', 'idempotency-key': k }), body: JSON.stringify({ cmd: id, args }), signal });
    } catch (err) {
      throw new WispError(`wisp at ${this.url}: ${err.message}`, { code: 'unavailable', retry: true });
    }
    const body = await r.json().catch(() => null);
    if (body?.ok === true) return body.result ?? null;
    const e = body?.error;
    throw new WispError(e?.message || `${id}: HTTP ${r.status}`, { code: e?.code || 'internal', status: r.status, retry: !!e?.retry, body });
  }

  /** Every command this caller may run, with its title and its args' TypeScript type. */
  catalogue() {
    return this.cmd('cli.catalogue', {});
  }

  // ---- tasks (runtime.*), the calls scripts use most ----

  /** Start a task: `{ prompt, cwd?, agent?, model?, effort?, mode?, worktree?, confirmLimit?, … }` (runtime.create). */
  run(spec) {
    return this.cmd('runtime.create', { cwd: process.cwd(), ...spec });
  }
  get(id) {
    return this.cmd('runtime.get', { id });
  }
  list(args = {}) {
    return this.cmd('runtime.list', args);
  }
  turns(id, args = {}) {
    return this.cmd('runtime.turns', { id, ...args });
  }
  presentation(id, args = {}) {
    return this.cmd('runtime.presentation', { id, ...args });
  }
  followUp(id, text, opts = {}) {
    return this.cmd('runtime.followUp', { id, text, attachments: [], ...opts });
  }
  stop(id) {
    return this.cmd('runtime.stop', { id });
  }
  /** Declare resources, as `wisp apply` does: the plan, applied unless `dryRun`. */
  apply(resources, { dryRun = false } = {}) {
    return this.cmd(dryRun ? 'resources.plan' : 'resources.apply', { resources });
  }

  /**
   * The sync stream for `topics` (`list`, `session:<id>`, …): yields its server messages (`welcome`, `snapshot`,
   * `patch`, `resync`, …) as they come. Read only: nothing is mutated through it. Ends with `signal`.
   */
  async *events(topics, { signal } = {}) {
    const q = new URLSearchParams({ proto_min: String(PROTO), proto_max: String(PROTO), client_id: this.clientId, build: 'wisp-agents-sdk', fresh: [].concat(topics).join(',') });
    const r = await fetch(`${this.url}/api/events?${q}`, { headers: this.#headers({ accept: 'text/event-stream' }), signal });
    if (!r.ok || !r.body) throw new WispError(`the sync stream said ${r.status}`, { code: 'unavailable', status: r.status, retry: true });
    const parser = new SseParser();
    const decoder = new TextDecoder();
    for await (const chunk of r.body) {
      for (const ev of parser.push(decoder.decode(chunk, { stream: true }))) {
        const messages = decodeFrame(ev);
        if (messages) yield* messages;
      }
    }
  }

  /**
   * Until the task stops working (`until(session)` true; by default: its state isn't `running`), or `timeoutMs`.
   * Live: each change on its topic is a look, never a timer.
   */
  async wait(id, { until = (s) => s.state !== 'running', timeoutMs = 30 * 60_000, signal } = {}) {
    const first = await this.get(id);
    if (until(first)) return first;
    const stop = new AbortController();
    const timer = setTimeout(() => stop.abort(new WispError(`${id} still works after ${Math.round(timeoutMs / 1000)} s`, { code: 'timeout' })), timeoutMs);
    signal?.addEventListener('abort', () => stop.abort(signal.reason), { once: true });
    try {
      for await (const m of this.events([`session:${id}`], { signal: stop.signal })) {
        if (m.t !== 'snapshot' && m.t !== 'patch') continue;
        const s = await this.get(id);
        if (until(s)) return s;
      }
      throw new WispError('the sync stream ended', { code: 'unavailable', retry: true });
    } catch (err) {
      throw stop.signal.aborted && stop.signal.reason instanceof Error ? stop.signal.reason : err;
    } finally {
      clearTimeout(timer);
      stop.abort();
    }
  }
}
