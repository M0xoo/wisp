//! `wisp sdk types ts|py`: the typed commands a running wisp lists, as the SDKs write them (`generateTypes()` in
//! `npm/wisp-agents/client.js`, `generate_stubs()` in `sdk/python/wisp`), byte for byte, so a build can write them
//! without Node or Python. ui-only commands are left out, as in both SDKs.

use crate::verbs::Catalogue;

fn ident(k: &str) -> bool {
    let mut c = k.chars();
    c.next().is_some_and(|f| f.is_ascii_alphabetic() || f == '_' || f == '$')
        && c.all(|x| x.is_ascii_alphanumeric() || x == '_' || x == '$')
}

fn quoted(s: &str) -> String {
    serde_json::to_string(s).unwrap_or_else(|_| format!("\"{s}\""))
}

/// The `.d.ts` (`ts`) or the `.pyi` (`py`); `None` for another language.
pub fn types(c: &Catalogue, lang: &str) -> Option<String> {
    let mut list: Vec<_> = c.verbs.iter().map(|v| &v.info).filter(|i| i.ui_only.is_none()).collect();
    list.sort_by(|a, b| a.id.cmp(&b.id));
    match lang {
        "ts" | "typescript" => {
            let mut l = vec![
                "// Generated by wisp-agents generateTypes() from a running wisp's catalogue. Do not edit.".to_owned(),
                "export interface WispCommands {".to_owned(),
            ];
            for i in list {
                if let Some(t) = i.title.as_deref().filter(|t| !t.is_empty()) {
                    l.push(format!("  /** {}{} */", t.replace("*/", "* /"), if i.read_only { " (read only)" } else { "" }));
                }
                let key = if ident(&i.id) { i.id.clone() } else { quoted(&i.id) };
                l.push(format!(
                    "  {key}: {{ args: {}; result: unknown }};",
                    i.args.as_deref().filter(|a| !a.is_empty()).unwrap_or("Record<string, unknown>")
                ));
            }
            l.extend(
                ["}", "", "declare module 'wisp-agents/client' {", "  interface WispClient {", "    cmd<K extends keyof WispCommands>(id: K, args: WispCommands[K]['args'], opts?: { key?: string }): Promise<WispCommands[K]['result']>;", "  }", "}", ""]
                    .map(str::to_owned),
            );
            Some(l.join("\n"))
        }
        "py" | "python" => {
            let mut l = [
                "# Generated by wisp.WispClient.generate_stubs() from a running wisp's catalogue. Do not edit.",
                "from typing import Any, Literal, overload",
                "",
                "class WispClient:",
            ]
            .map(str::to_owned)
            .to_vec();
            for i in list {
                l.push("    @overload".to_owned());
                l.push(format!(
                    "    def cmd(self, command: Literal[{}], args: dict[str, Any] | None = ..., /, **kw: Any) -> Any: ...",
                    quoted(&i.id)
                ));
                if let Some(t) = i.title.as_deref().filter(|t| !t.is_empty()) {
                    l.push(format!("    # {}", t.replace("\"\"\"", "'''")));
                }
            }
            l.push("    def cmd(self, command: str, args: dict[str, Any] | None = ..., /, **kw: Any) -> Any: ...".to_owned());
            Some(l.join("\n") + "\n")
        }
        _ => None,
    }
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    use wisp_kernel::CommandInfo;

    fn info(id: &str, title: Option<&str>, args: Option<&str>, read_only: bool, ui_only: bool) -> CommandInfo {
        serde_json::from_value(serde_json::json!({ "id": id, "plugin": "p", "title": title, "readOnly": read_only, "permission": id, "args": args, "uiOnly": ui_only.then_some("a pane") })).unwrap()
    }

    /// The same text the TypeScript and Python SDKs generate (npm/test/client.test.mjs's case), sorted by id, ui-only
    /// commands left out, an id that isn't an identifier quoted.
    #[test]
    fn sdk_types_are_what_the_sdks_generate_from_the_catalogue() {
        let c = Catalogue::new(vec![
            info("runtime.get", Some("A task */ x"), Some("{ id: string }"), true, false),
            info("crew.list", None, None, false, false),
            info("shell.pane", Some("ui"), None, false, true),
        ]);
        let ts = types(&c, "ts").unwrap();
        assert!(ts.starts_with(
            "// Generated by wisp-agents generateTypes() from a running wisp's catalogue. Do not edit.\nexport interface WispCommands {\n"
        ));
        assert!(ts.contains("  \"crew.list\": { args: Record<string, unknown>; result: unknown };\n  /** A task * / x (read only) */\n  \"runtime.get\": { args: { id: string }; result: unknown };\n}\n"));
        assert!(!ts.contains("shell.pane") && ts.ends_with("  }\n}\n"));
        let py = types(&c, "py").unwrap();
        assert!(py.contains("    @overload\n    def cmd(self, command: Literal[\"crew.list\"], args: dict[str, Any] | None = ..., /, **kw: Any) -> Any: ...\n    @overload\n"));
        assert!(py.contains("Literal[\"runtime.get\"]") && py.contains("    # A task */ x\n") && !py.contains("shell.pane"));
        assert!(types(&c, "go").is_none());
    }
}
